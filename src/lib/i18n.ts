const LANGUAGE_STORAGE_KEY = 'panorama-language'

export function translate(
  language: Language,
  key: TranslationKey,
  variables: Record<string, string | number> = {},
) {
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    translations[language][key],
  )
}

export function localizedCountryName(language: Language, code: string, fallback: string) {
  return countries.getName(code, countryLocale[language]) ?? aggregateNames[code]?.[language] ?? fallback
}

export function localeFor(language: Language) {
  if (language === 'pt-BR') return 'pt-BR'
  if (language === 'es') return 'es-ES'
  return 'en-US'
}

export function getInitialLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (saved === 'pt-BR' || saved === 'en' || saved === 'es') return saved
  } catch {
    // A preferência do navegador continua disponível sem armazenamento persistente.
  }

  const browserLanguage = navigator.languages?.[0] ?? navigator.language
  if (browserLanguage.toLowerCase().startsWith('es')) return 'es'
  if (browserLanguage.toLowerCase().startsWith('en')) return 'en'
  return 'pt-BR'
}

export function applyLanguage(language: Language) {
  document.documentElement.lang = language
  document.title = translate(language, 'meta.title')
  const title = translate(language, 'meta.title')
  const description = translate(language, 'meta.description')
  document.querySelector('meta[name="description"]')?.setAttribute('content', description)
  document.querySelector('meta[property="og:title"]')?.setAttribute('content', title)
  document.querySelector('meta[property="og:description"]')?.setAttribute('content', description)
  document.querySelector('meta[name="twitter:title"]')?.setAttribute('content', title)
  document.querySelector('meta[name="twitter:description"]')?.setAttribute('content', description)
}

export function saveLanguage(language: Language) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
  } catch {
    // A troca funciona durante a sessão mesmo sem persistência.
  }
  applyLanguage(language)
}
